    fun getLocalizedSymptom(context: Context, rawSymptom: String): String {
        if (rawSymptom.isBlank()) return rawSymptom
        val lang = LocaleHelper.getSavedLanguageCode(context).lowercase()
        val map = when {
            lang.startsWith("ar") -> arTranslations
            lang.startsWith("hi") -> hiTranslations
            lang.startsWith("vi") -> viTranslations
            lang.startsWith("es") -> esTranslations
            lang.startsWith("fr") -> frTranslations
            lang.startsWith("de") -> deTranslations
            lang.startsWith("pt") -> ptTranslations
            lang.startsWith("ru") -> ruTranslations
            lang.startsWith("ja") -> jaTranslations
            lang.startsWith("ko") -> koTranslations
            lang.startsWith("zh") -> zhTranslations
            lang.startsWith("id") || lang.startsWith("in") -> idTranslations
            lang.startsWith("tr") -> trTranslations
            lang.startsWith("bn") -> bnTranslations
            else -> null
        }
        return map?.get(rawSymptom) ?: rawSymptom
    }
