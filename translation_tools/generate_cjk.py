def generate(trans, folder):
    with open(en_file, 'r', encoding='utf-8') as f:
        lines = f.readlines()
    out = []
    for line in lines:
        m = re.search(r'<string name="([^"]+)">([^<]+)</string>', line)
        if m:
            k = m.group(1)
            orig = m.group(2)
            v = trans.get(k, orig)
            indent = line[:line.find('<string')]
            out.append(f'{indent}<string name="{k}">{v}</string>\n')
        else:
            out.append(line)
    os.makedirs(folder, exist_ok=True)
    with open(f'{folder}/strings.xml', 'w', encoding='utf-8') as f:
        f.writelines(out)
    print(f"Generated {folder}/strings.xml")

